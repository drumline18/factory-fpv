#include "RadioArm.h"
#include <iostream>
#include <stdexcept>
using namespace factoryfpv;
int main() {
 int count=0;
 auto check=[&](bool value,const char* name) { if(!value) throw std::runtime_error(name);++count; };
 std::array<long,8> off{},on{};
 std::array<bool,128> bo{},bn{};
 std::array<RadioAxisInfo,8> info{};
 for(auto& item:info) item={true,0,65535};
 const std::array<int,4> sticks{0,1,3,2};
 ArmBinding binding;
 bn[5]=true;
 check(learnArmBinding(off,bo,on,bn,info,sticks,binding) && binding.kind==1 && binding.index==5,"button detection");
 check(binding.position(off,bo,true)==ArmPosition::Off,"button off");
 check(binding.position(on,bn,true)==ArmPosition::On,"button on");
 check(binding.position(on,bn,false)==ArmPosition::Lost,"disconnect beats held switch");
 ArmBinding inverted{1,5,1,0};
 check(inverted.position(off,bo,true)==ArmPosition::On,"inverted button");
 std::array<bool,128> presentButtons{};
 check(!inverted.available(info,presentButtons),"absent inverted button is unavailable");
 presentButtons[5]=true;
 check(inverted.available(info,presentButtons),"reported inverted button is available");
 presentButtons[127]=true;
 check(ArmBinding{1,127,0,1}.available(info,presentButtons),"last button slot can be reported");
 check(!ArmBinding{1,128,0,1}.available(info,presentButtons),"out-of-range button cannot be available");
 check(!ArmBinding{}.available(info,presentButtons),"unbound control has no physical capability");
 bn[6]=true;
 check(!learnArmBinding(off,bo,on,bn,info,sticks,binding),"ambiguous buttons rejected");
 bn={};on[4]=65535;
 check(learnArmBinding(off,bo,on,bn,info,sticks,binding) && binding.kind==2 && binding.index==4,"aux axis detection");
 check(binding.position(on,bn,true)==ArmPosition::On,"axis on");
 on[4]=32767;
 check(binding.position(on,bn,true)==ArmPosition::Middle,"three-position middle disarms");
 ArmBinding reverse{2,4,65535,0};
 check(reverse.position(off,bo,true)==ArmPosition::On,"reverse aux axis");
 check(reverse.available(info,presentButtons),"reported inverted auxiliary axis is available");
 auto missingAux=info;
 missingAux[4].present=false;
 check(!reverse.available(missingAux,presentButtons),"absent inverted auxiliary axis is unavailable");
 check(!ArmBinding{2,8,0,65535}.available(info,presentButtons),"out-of-range auxiliary axis cannot be available");
 on={};on[0]=65535;
 check(!learnArmBinding(off,bo,on,bn,info,sticks,binding),"flight controls excluded");
 on[4]=65535;bn[0]=true;
 check(!learnArmBinding(off,bo,on,bn,info,sticks,binding),"mixed axis and button ambiguity");
 bn={};on[4]=2000;
 check(!learnArmBinding(off,bo,on,bn,info,sticks,binding),"axis noise rejected");
 check(!ArmBinding{2,99,0,65535}.valid(),"bad index rejected");
 check(!ArmBinding{2,4,10,10}.valid(),"zero range rejected");
 RadioArmGate gate;
 check(!gate.update(ArmPosition::On).arm,"startup held-on never arms");
 check(gate.update(ArmPosition::Off).disarm,"off always cuts thrust");
 check(gate.update(ArmPosition::On).arm,"fresh off-on requests arm");
 check(!gate.update(ArmPosition::On).arm,"held-on does not repeat rejected request");
 gate.update(ArmPosition::Off);gate.reset();
 check(!gate.update(ArmPosition::On).arm,"pause/reset consumes prior off");
 gate.update(ArmPosition::Off);gate.update(ArmPosition::Lost);
 check(!gate.update(ArmPosition::On).arm,"reconnect held-on cannot arm");
 gate.update(ArmPosition::Off);
 check(gate.update(ArmPosition::Middle).disarm,"middle cuts thrust");
 check(gate.update(ArmPosition::On).arm,"three-way off-middle-on works");
 FlightCore flight;
 Input input{0,0,0,.8,true};
 gate.update(ArmPosition::Off);
 auto action=gate.update(ArmPosition::On);
 if(action.arm) flight.arm(input);
 check(!flight.armed,"high throttle refuses arming");
 input.throttle=0;
 action=gate.update(ArmPosition::On);
 if(action.arm) flight.arm(input);
 check(!flight.armed,"lower throttle while still on cannot arm");
 gate.update(ArmPosition::Off);action=gate.update(ArmPosition::On);
 if(action.arm) flight.arm(input);
 check(flight.armed,"fresh low-throttle cycle arms");
 std::cout<<count<<" radio arm checks passed\n";
}
